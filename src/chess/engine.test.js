import test from 'node:test'
import assert from 'node:assert/strict'
import { initialState, fromFEN, makeMove, makeMoveAndClaim, legalMoves, inCheck, outcome, square, positionKey, resign, drawClaims, claimDraw } from './engine.js'
const play = (state, ...moves) => moves.reduce((s,m) => makeMove(s,{from:m.slice(0,2),to:m.slice(2,4),...(m[4] ? {promotion:m[4]} : {})}),state)
const destinations = (state,from) => legalMoves(state,square(from)).map(m => m.to)

test('opening moves and immutable state', () => {
  const state = initialState(), snapshot = JSON.stringify(state)
  assert.equal(legalMoves(state).length,20)
  const next = play(state,'e2e4')
  assert.equal(next.board[square('e4')],'P'); assert.equal(next.turn,'b')
  assert.equal(next.ep,square('e3')); assert.equal(next.halfmove,0)
  assert.equal(JSON.stringify(state),snapshot)
  assert.throws(() => play(state,'e2e5')); assert.throws(() => play(state,'e7e5'))
})
test('opening perft depth 3 is 8902 legal positions', () => {
  const count = (s,d) => d === 0 ? 1 : legalMoves(s).reduce((n,m) => n+count(makeMove(s,m),d-1),0)
  assert.equal(count(initialState(),3),8902)
})
test('Kiwipete perft validates castling, captures and checks through depth 3', () => {
  const state = fromFEN('r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1')
  const count = (s,d) => d === 0 ? 1 : legalMoves(s).reduce((n,m) => n+count(makeMove(s,m),d-1),0)
  assert.deepEqual([1,2,3].map(d => count(state,d)),[48,2039,97862])
})
test('fools mate, terminal lock, resignation and previous immutable positions', () => {
  const state = initialState(), mate = play(state,'f2f3','e7e5','g2g4','d8h4')
  assert.equal(inCheck(mate),true)
  assert.deepEqual(mate.result,{winner:'b',reason:'checkmate'})
  assert.throws(() => play(mate,'a2a3'))
  assert.deepEqual(resign(state).result,{winner:'b',reason:'resignation'})
  assert.equal(state.result,null); assert.equal(legalMoves(state).length,20)
})
test('resignation is a draw when the opponent has only a bare king', () => {
  for (const fen of ['7k/8/8/8/8/8/Q7/K7 w - - 0 1','7k/7q/8/8/8/8/8/K7 b - - 0 1']) {
    const state = fromFEN(fen), snapshot = JSON.stringify(state)
    assert.equal(outcome(state),null)
    assert.deepEqual(resign(state).result,{winner:null,reason:'resignation-no-mating-material'})
    assert.equal(JSON.stringify(state),snapshot)
  }
  assert.throws(() => resign(fromFEN('7k/8/8/8/8/8/8/KB6 w - - 0 1')))
})
test('pinned pieces cannot expose king and kings cannot be captured', () => {
  const s = fromFEN('4r1k1/8/8/8/8/8/4R3/4K3 w - - 0 1')
  assert.throws(() => play(s,'e2d2')); assert.ok(destinations(s,'e2').includes(square('e8')))
  assert.equal(legalMoves(fromFEN('4k3/8/8/8/8/8/4Q3/4K3 w - - 0 1')).some(m => m.to === square('e8')),false)
})
test('castling moves rook, clears rights, rejects check, attacked transit and destination', () => {
  const s = fromFEN('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1')
  for (const target of ['g1','c1']) assert.ok(destinations(s,'e1').includes(square(target)))
  const next = play(s,'e1g1')
  assert.equal(next.board[square('f1')],'R'); assert.equal(next.board[square('h1')],null)
  assert.equal(next.castling,'kq')
  for (const fen of ['4kr2/8/8/8/8/8/8/4K2R w K - 0 1','4k1r1/8/8/8/8/8/8/4K2R w K - 0 1','4r1k1/8/8/8/8/8/8/4K2R w K - 0 1','4k3/8/8/8/8/8/8/4K3 w K - 0 1']) assert.equal(destinations(fromFEN(fen),'e1').includes(square('g1')),false)
  const moved = play(s,'h1h2','h8h7','h2h1','h7h8')
  assert.equal(moved.castling.includes('K'),false)
  assert.equal(play(fromFEN('r3k2r/8/8/8/8/8/7Q/4K3 w kq - 0 1'),'h2h8').castling,'q')
})
test('en passant capture, expiration and discovered check', () => {
  const state = play(initialState(),'e2e4','a7a6','e4e5','d7d5')
  const next = play(state,'e5d6')
  assert.equal(next.board[square('d5')],null); assert.equal(next.board[square('d6')],'P')
  assert.equal(next.halfmove,0)
  assert.throws(() => play(play(state,'a2a3','a6a5'),'e5d6'))
  const pinned = fromFEN('4k3/8/8/r4pPK/8/8/8/8 w - f6 0 1')
  assert.equal(destinations(pinned,'g5').includes(square('f6')),false)
})
test('promotion requires explicit valid choice and can capture / underpromote', () => {
  const s = fromFEN('1r5k/P7/8/8/8/8/8/7K w - - 0 1')
  assert.equal(legalMoves(s,square('a7')).length,8)
  assert.throws(() => play(s,'a7a8')); assert.throws(() => play(s,'a7a8k'))
  for (const p of ['q','r','b','n']) assert.equal(play(s,'a7b8'+p).board[square('b8')],p.toUpperCase())
})
test('stalemate differs from checkmate', () => {
  assert.deepEqual(outcome(fromFEN('7k/5Q2/6K1/8/8/8/8/8 b - - 0 1')),{winner:null,reason:'stalemate'})
  assert.deepEqual(outcome(fromFEN('7k/6Q1/6K1/8/8/8/8/8 b - - 0 1')),{winner:'w',reason:'checkmate'})
})
test('threefold repetition keys include turn, rights and only capturable en passant', () => {
  const repeated = play(initialState(),'g1f3','g8f6','f3g1','f6g8','g1f3','g8f6','f3g1','f6g8')
  assert.equal(repeated.result,null)
  assert.deepEqual(drawClaims(repeated),['repetition'])
  assert.deepEqual(claimDraw(repeated).result,{winner:null,reason:'repetition'})
  assert.throws(() => claimDraw(initialState()))
  const fivefold = play(repeated,'g1f3','g8f6','f3g1','f6g8','g1f3','g8f6','f3g1','f6g8')
  assert.equal(fivefold.result.reason,'fivefold-repetition')
  const a = fromFEN('4k3/8/8/8/4P3/8/8/4K3 b - e3 0 1'), b = fromFEN('4k3/8/8/8/4P3/8/8/4K3 b - - 0 1')
  assert.equal(positionKey(a),positionKey(b))
  assert.notEqual(positionKey(initialState()),positionKey({...initialState(),castling:''}))
  const c = fromFEN('4k3/8/8/8/3pP3/8/8/4K3 b - e3 0 1')
  assert.notEqual(positionKey(c),positionKey({...c,ep:null}))
})
test('50 move draw, reset on pawn/capture and mate precedence', () => {
  const fifty = play(fromFEN('7k/8/8/8/8/8/P7/K6R w - - 99 1'),'h1h2')
  assert.deepEqual(drawClaims(fifty),['fifty-move'])
  assert.equal(claimDraw(fifty).result.reason,'fifty-move')
  assert.equal(play(fromFEN('7k/8/8/8/8/8/P7/K6R w - - 149 1'),'h1h2').result.reason,'seventy-five-move')
  assert.equal(play(fromFEN('7k/8/8/8/8/8/P7/K6R w - - 99 1'),'a2a3').halfmove,0)
  assert.equal(play(fromFEN('7k/8/8/8/8/8/7p/K6R w - - 99 1'),'h1h2').halfmove,0)
  assert.equal(play(fromFEN('7k/8/5KQ1/8/8/8/8/8 w - - 149 1'),'g6g7').result.reason,'checkmate')
})
test('announced move can claim before giving the turn to the opponent', () => {
  const state = play(initialState(),'g1f3','g8f6','f3g1','f6g8','g1f3','g8f6','f3g1')
  assert.deepEqual(makeMoveAndClaim(state,{from:'f6',to:'g8'}).result,{winner:null,reason:'repetition'})
  assert.equal(makeMoveAndClaim(initialState(),{from:'e2',to:'e4'}).result,null)
})
test('insufficient material recognizes dead positions without declaring two knights dead', () => {
  for (const fen of ['7k/8/8/8/8/8/8/K7 w - - 0 1','7k/8/8/8/8/8/8/KN6 w - - 0 1','7k/8/8/8/8/8/8/KB6 w - - 0 1','7k/8/8/8/5b2/8/8/K1B5 w - - 0 1']) assert.equal(outcome(fromFEN(fen)).reason,'insufficient-material')
  assert.equal(outcome(fromFEN('7k/8/8/8/8/8/8/KNN5 w - - 0 1')),null)
})

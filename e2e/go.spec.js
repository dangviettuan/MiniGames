test('long 19x19 game fits browser storage and restores undo/redo history', async ({ page }) => {
  let game = createGame(19), moves = 0
  for (let attempt = 0; moves < 300 && attempt < 3610; attempt++) {
    const result = play(game, attempt % 361)
    if (result.ok) { game = result.state; moves++ }
  }
  game = undo(undo(game))
  const record = JSON.stringify({ version: 1, data: encodeGo(game) })
  expect(Buffer.byteLength(record)).toBeLessThan(1_000_000)
  await page.evaluate(record => localStorage.setItem('minigames:game:v1:go', record), record)
  await page.reload()
  await expect(page.getByRole('grid', { name: 'Bàn cờ vây 19 × 19' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.reload()
  const restored = decodeGo(await page.evaluate(() => JSON.parse(localStorage.getItem('minigames:game:v1:go')).data))
  expect(restored.past).toHaveLength(299)
  expect(restored.future).toHaveLength(1)
  expect(restored.positions).toHaveLength(300)
  await expect(page.locator('.play-save-warning')).toHaveCount(0)
})

test('new game after undoing all moves protects redo until reset is confirmed', async ({ page }) => {
  const undoButton = page.getByRole('button', { name: 'Undo', exact: true })
  const redoButton = page.getByRole('button', { name: 'Redo', exact: true })
  const dialog = page.getByRole('dialog', { name: 'Bắt đầu ván cờ vây mới?' })
  await place(page, 0, 0)
  await place(page, 0, 1)
  await undoButton.click()
  await undoButton.click()
  await expect(undoButton).toBeDisabled()
  await expect(redoButton).toBeEnabled()
  await expect(page.locator('.go-black, .go-white')).toHaveCount(0)

  await tools(page)
  await page.getByRole('button', { name: 'Ván mới', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Giữ ván hiện tại', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(undoButton).toBeDisabled()
  await expect(redoButton).toBeEnabled()
  await redoButton.click()
  await expect(point(page, 0, 0)).toHaveAttribute('aria-label', /Đen/)
  await expect(status(page)).toHaveText('Lượt Trắng')
  await redoButton.click()
  await expect(point(page, 0, 1)).toHaveAttribute('aria-label', /Trắng/)
  await expect(status(page)).toHaveText('Lượt Đen')
  await expect(redoButton).toBeDisabled()

  await undoButton.click()
  await undoButton.click()
  await tools(page)
  await page.getByRole('button', { name: 'Ván mới', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Bắt đầu ván mới', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(undoButton).toBeDisabled()
  await expect(redoButton).toBeDisabled()
  await page.reload()
  await expect(status(page)).toHaveText('Lượt Đen')
  await expect(page.locator('.go-black, .go-white')).toHaveCount(0)
  await expect(undoButton).toBeDisabled()
  await expect(redoButton).toBeDisabled()
})


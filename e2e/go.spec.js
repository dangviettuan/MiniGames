import { test, expect } from '@playwright/test'

const point = (page, row, col) => page.getByTestId(`go-${row}-${col}`)
const status = page => page.getByTestId('go-status')
async function capture(page) {
  await point(page, 0, 1).click()
  await point(page, 0, 0).click()
  await point(page, 1, 0).click()
}
async function scoring(page) {
  await page.getByRole('button', { name: 'Bỏ lượt', exact: true }).click()
  await page.getByRole('button', { name: 'Bỏ lượt', exact: true }).click()
  await expect(status(page)).toContainText('Tính điểm')
}

test.beforeEach(async ({ page }) => { await page.goto('/MiniGames/#go') })

test('legal play captures, undo/redo restores prisoners, occupied points are unavailable', async ({ page }) => {
  await expect(page.getByRole('grid', { name: 'Bàn cờ vây 9 × 9' })).toBeVisible()
  await capture(page)
  await expect(point(page, 0, 0)).toHaveAttribute('aria-label', 'A9, trống')
  await expect(page.getByTestId('go-captures')).toContainText('Đen 1')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(point(page, 0, 0)).toHaveAttribute('aria-label', /Trắng/)
  await expect(page.getByTestId('go-captures')).toContainText('Đen 0')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(point(page, 0, 0)).toHaveAttribute('aria-label', /trống/)
  // aria-disabled communicates occupied points; engine validation is covered in unit tests.
  await expect(point(page, 0, 1)).toHaveAttribute('aria-disabled', 'true')
  await expect(status(page)).toHaveText('Lượt Trắng')
})

test('two passes, mutual dead-group agreement, final score, undo/redo and reset', async ({ page }) => {
  await capture(page)
  await scoring(page)
  await point(page, 0, 1).click()
  await expect(point(page, 0, 1)).toHaveAttribute('aria-label', /quân chết/)
  await page.getByRole('button', { name: 'Đen xác nhận điểm', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Đen đã xác nhận', exact: true })).toBeDisabled()
  await point(page, 1, 0).click()
  await expect(page.getByRole('button', { name: 'Đen xác nhận điểm', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Đen xác nhận điểm', exact: true }).click()
  await page.getByRole('button', { name: 'Trắng xác nhận điểm', exact: true }).click()
  await expect(status(page)).toHaveText('Trắng thắng 7.5 điểm.')
  await expect(page.getByRole('button', { name: 'Bỏ lượt', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(status(page)).toContainText('Tính điểm')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(status(page)).toContainText('Trắng thắng')
  await page.getByRole('button', { name: 'Ván mới', exact: true }).click()
  await page.getByRole('button', { name: 'Bắt đầu ván mới', exact: true }).click()
  await expect(status(page)).toHaveText('Lượt Đen')
  await expect(point(page, 0, 1)).toHaveAttribute('aria-label', /trống/)
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeDisabled()
})

test('score disagreement resumes play, new move truncates redo, resignation is reversible', async ({ page }) => {
  await point(page, 0, 0).click()
  await scoring(page)
  await point(page, 0, 0).click()
  await page.getByRole('button', { name: 'Không đồng ý — chơi tiếp', exact: true }).click()
  await expect(status(page)).toHaveText('Lượt Trắng')
  await expect(point(page, 0, 0)).not.toHaveAttribute('aria-label', /quân chết/)
  await point(page, 8, 8).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await point(page, 8, 7).click()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Đầu hàng', exact: true }).click()
  await page.getByRole('button', { name: 'Đen xác nhận đầu hàng', exact: true }).click()
  await expect(status(page)).toHaveText('Trắng thắng do đối phương đầu hàng.')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(status(page)).toHaveText('Lượt Đen')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(status(page)).toContainText('Trắng thắng')
})

test('board size changes, keyboard navigation, and large boards scroll without page overflow', async ({ page }) => {
  await point(page, 0, 0).focus()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Enter')
  await expect(point(page, 0, 1)).toHaveAttribute('aria-label', /Đen/)
  for (const size of [13, 19]) {
    await page.getByLabel('Cỡ bàn ván mới').selectOption(String(size))
    await page.getByRole('button', { name: 'Ván mới', exact: true }).click()
    if (await page.getByRole('button', { name: 'Bắt đầu ván mới', exact: true }).isVisible()) await page.getByRole('button', { name: 'Bắt đầu ván mới', exact: true }).click()
    const board = page.getByRole('grid', { name: `Bàn cờ vây ${size} × ${size}` })
    await expect(board.getByRole('button')).toHaveCount(size * size)
    await point(page, size - 1, size - 1).click()
    await expect(point(page, size - 1, size - 1)).toHaveAttribute('aria-label', /Đen/)
    const bounds = await point(page, size - 1, size - 1).boundingBox()
    expect(bounds.width).toBeGreaterThanOrEqual(31.9)
    expect(bounds.height).toBeGreaterThanOrEqual(31.9)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (size === 19 && page.viewportSize().width <= 760) await expect(page.getByRole('button', { name: 'Bỏ lượt', exact: true })).toBeInViewport()
  }
})

test('suicide reports an actionable error without switching the player', async ({ page }) => {
  for (const [row, col] of [[8, 8], [0, 1], [8, 7], [1, 0]]) await point(page, row, col).click()
  await point(page, 0, 0).click()
  await expect(page.getByRole('alert')).toContainText('Không được tự sát')
  await expect(point(page, 0, 0)).toHaveAttribute('aria-label', /trống/)
  await expect(status(page)).toHaveText('Lượt Đen')
  await point(page, 8, 6).click()
  await expect(page.getByRole('alert')).not.toBeVisible()
  await expect(status(page)).toHaveText('Lượt Trắng')
})

test('real ko capture rejects recapture and black score victory needs both confirmations', async ({ page }) => {
  for (const [row, col] of [[0, 1], [0, 2], [1, 0], [2, 2], [2, 1], [1, 3], [8, 8], [1, 1], [1, 2]]) await point(page, row, col).click()
  await expect(point(page, 1, 1)).toHaveAttribute('aria-label', /trống/)
  await point(page, 1, 1).click()
  await expect(page.getByRole('alert')).toContainText('Superko')
  await expect(status(page)).toHaveText('Lượt Trắng')
  await page.getByRole('button', { name: 'Ván mới', exact: true }).click()
  await page.getByRole('button', { name: 'Bắt đầu ván mới', exact: true }).click()
  await point(page, 4, 4).click()
  await scoring(page)
  await page.getByRole('button', { name: 'Trắng xác nhận điểm', exact: true }).click()
  await expect(status(page)).toContainText('Tính điểm')
  await page.getByRole('button', { name: 'Đen xác nhận điểm', exact: true }).click()
  await expect(status(page)).toHaveText('Đen thắng 73.5 điểm.')
})

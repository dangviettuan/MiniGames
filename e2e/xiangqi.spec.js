import { test, expect } from '@playwright/test'
test('board renders and a legal move can be undone and redone', async ({ page }) => {
 await page.goto('/')
 const board = page.getByRole('grid', { name: 'Bàn cờ tướng' })
 await expect(board.locator('button')).toHaveCount(90)
 const from = board.getByRole('button', { name: /Hàng 7, cột 1, Đỏ soldier/ })
 const to = board.getByRole('button', { name: /Hàng 6, cột 1, trống/ })
 await from.click()
 await expect(to).toHaveAttribute('aria-label', /có thể đi tới/)
 await to.click()
 await expect(board.getByRole('button', { name: /Hàng 6, cột 1, Đỏ soldier/ })).toBeVisible()
 await page.getByRole('button', { name: /Undo/ }).click()
 await expect(board.getByRole('button', { name: /Hàng 7, cột 1, Đỏ soldier/ })).toBeVisible()
 await page.getByRole('button', { name: /Redo/ }).click()
 await expect(board.getByRole('button', { name: /Hàng 6, cột 1, Đỏ soldier/ })).toBeVisible()
})
test('new game resets board and timeline', async ({ page }) => {
 await page.goto('/')
 const board = page.getByRole('grid', { name: 'Bàn cờ tướng' })
 await board.getByRole('button', { name: /Hàng 7, cột 1, Đỏ soldier/ }).click()
 await board.getByRole('button', { name: /Hàng 6, cột 1, trống/ }).click()
 await page.getByRole('button', { name: 'Ván mới' }).click()
 await expect(board.getByRole('button', { name: /Hàng 7, cột 1, Đỏ soldier/ })).toBeVisible()
 await expect(page.getByRole('button', { name: /Undo/ })).toBeDisabled()
})

test('responsive board fits viewport and action controls stay beside gameplay', async ({page}) => {
  const board = page.getByRole('grid',{name:'Bàn cờ vua'}), bounds = await board.boundingBox(), viewport = page.viewportSize()
  expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(viewport.width)
  expect(Math.abs(bounds.width-bounds.height)).toBeLessThan(2)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeInViewport()
  await move(page,'e2','e4')
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
})

test('reload preserves timeline, redo, orientation and preferences; cancelled reset changes nothing', async ({page}) => {
  await move(page,'e2','e4');await move(page,'e7','e5')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await tool(page,'Xoay bàn')
  await page.getByLabel('Tùy chọn Cờ vua',{exact:true}).click()
  await page.getByRole('checkbox',{name:'Yêu cầu hòa nếu nước tiếp theo đủ điều kiện'}).check()
  await page.reload()
  await expect(page.getByRole('status')).toHaveText('Lượt Đen')
  await expect(page.getByRole('grid',{name:'Bàn cờ vua'}).locator('button').first()).toHaveAttribute('data-square','h1')
  await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeEnabled()
  await tool(page,'Ván mới')
  await page.getByRole('dialog').getByRole('button',{name:'Tiếp tục ván này'}).click()
  await page.reload()
  await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(cell(page,'e5')).toHaveAttribute('aria-label',/Đen Tốt/)
  await tool(page,'Xoay bàn')
  await page.getByLabel('Tùy chọn Cờ vua',{exact:true}).click()
  await expect(page.getByRole('checkbox',{name:'Yêu cầu hòa nếu nước tiếp theo đủ điều kiện'})).toBeChecked()
  await newGame(page);await page.reload()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeDisabled()
})

test('corrupt saves fall back safely to the initial position', async ({page}) => {
  await move(page,'e2','e4')
  await page.evaluate(() => {
    const key='minigames:game:v1:chess', saved=JSON.parse(localStorage.getItem(key))
    saved.data.timeline[1].castling='';localStorage.setItem(key,JSON.stringify(saved))
  })
  await page.reload()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeDisabled()
  await page.evaluate(() => localStorage.setItem('minigames:game:v1:chess','{broken'))
  await page.reload()
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
})

test('six target dimensions keep board readable, pieces inside cells and controls visible', async ({page}) => {
  for(const [width,height] of [[1366,768],[834,1194],[1194,834],[393,851],[360,640],[851,393]]) {
    await page.setViewportSize({width,height})
    const box=await page.getByRole('grid',{name:'Bàn cờ vua'}).boundingBox()
    expect(box.width,`${width}x${height} board width`).toBeGreaterThanOrEqual(300)
    expect(box.y+box.height,`${width}x${height} board bottom`).toBeLessThanOrEqual(height)
    const piece=await cell(page,'e2').locator('.chess-piece').boundingBox(), square=await cell(page,'e2').boundingBox()
    expect(piece.width).toBeLessThanOrEqual(square.width);expect(piece.height).toBeLessThanOrEqual(square.height)
    await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeInViewport()
    await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth>innerWidth)).toBe(false)
  }
})


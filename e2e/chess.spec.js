import { test, expect } from '@playwright/test'
const cell = (page,square) => page.locator(`[data-square="${square}"]`)
async function move(page,from,to) { await cell(page,from).click(); await cell(page,to).click() }
async function tool(page,name) {
  if (!await page.locator('.play-chess .play-tools').evaluate(el => el.open)) await page.getByLabel('Tùy chọn Cờ vua',{exact:true}).click()
  await page.getByRole('button',{name,exact:true}).click()
}
async function newGame(page) { await tool(page,'Ván mới');await page.getByRole('dialog',{name:'Tạo ván mới?'}).getByRole('button',{name:'Tạo ván mới',exact:true}).click() }
test.beforeEach(async ({page}) => { await page.goto('./#chess'); await expect(page.getByRole('grid',{name:'Bàn cờ vua'})).toBeVisible() })

test('legal / invalid moves, undo redo, branch, flip and reset', async ({page}) => {
  await expect(page.getByRole('grid',{name:'Bàn cờ vua'}).locator('button')).toHaveCount(64)
  await cell(page,'e2').click(); await cell(page,'e5').click()
  await expect(page.getByRole('alert')).toContainText('không hợp lệ')
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await cell(page,'e4').click()
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(page.getByRole('status')).toContainText('Lượt Đen')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await move(page,'d2','d4')
  await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeDisabled()
  await tool(page,'Xoay bàn')
  await expect(page.getByRole('grid',{name:'Bàn cờ vua'}).locator('button').first()).toHaveAttribute('data-square','h1')
  await newGame(page)
  await expect(cell(page,'d2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeDisabled()
})

test('play fools mate, restore terminal result and start again', async ({page}) => {
  await move(page,'f2','f3');await move(page,'e7','e5');await move(page,'g2','g4');await move(page,'d8','h4')
  await expect(page.getByRole('status')).toHaveText('Đen thắng — chiếu hết.')
  await expect(cell(page,'e2')).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('status')).toContainText('chiếu hết')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Đen')
  await expect(cell(page,'d8')).toHaveAttribute('aria-label',/Đen Hậu/)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('chiếu hết')
  await newGame(page)
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
})


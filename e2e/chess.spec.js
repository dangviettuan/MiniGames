import { test, expect } from '@playwright/test'
const cell = (page,square) => page.locator(`[data-square="${square}"]`)
async function move(page,from,to) { await cell(page,from).click(); await cell(page,to).click() }
test.beforeEach(async ({page}) => { await page.goto('./#chess'); await expect(page.getByRole('grid',{name:'Bàn cờ vua'})).toBeVisible() })

test('legal / invalid moves, undo redo, branch, flip and reset', async ({page}) => {
  await expect(page.getByRole('grid',{name:'Bàn cờ vua'}).locator('button')).toHaveCount(64)
  await cell(page,'e2').click(); await cell(page,'e5').click()
  await expect(page.getByRole('alert')).toContainText('không hợp lệ')
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await cell(page,'e4').click()
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(page.getByRole('status')).toContainText('Lượt Đen')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(cell(page,'e2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await move(page,'d2','d4')
  await expect(page.getByRole('button',{name:'Redo',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Xoay bàn',exact:true}).click()
  await expect(page.getByRole('grid',{name:'Bàn cờ vua'}).locator('button').first()).toHaveAttribute('data-square','h1')
  await page.getByRole('button',{name:'Ván mới',exact:true}).click()
  await expect(cell(page,'d2')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeDisabled()
})

test('play fools mate, restore terminal result and start again', async ({page}) => {
  await move(page,'f2','f3');await move(page,'e7','e5');await move(page,'g2','g4');await move(page,'d8','h4')
  await expect(page.getByRole('status')).toHaveText('Đen thắng — chiếu hết.')
  await expect(cell(page,'e2')).toBeDisabled()
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Đen')
  await expect(cell(page,'d8')).toHaveAttribute('aria-label',/Đen Hậu/)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('chiếu hết')
  await page.getByRole('button',{name:'Ván mới',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
})

test('castle through a legal opening and undo rook and king together', async ({page}) => {
  for (const [a,b] of [['e2','e4'],['e7','e5'],['g1','f3'],['b8','c6'],['f1','c4'],['g8','f6'],['e1','g1']]) await move(page,a,b)
  await expect(cell(page,'g1')).toHaveAttribute('aria-label',/Trắng Vua/)
  await expect(cell(page,'f1')).toHaveAttribute('aria-label',/Trắng Xe/)
  await expect(cell(page,'h1')).toHaveAttribute('aria-label',/trống/)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(cell(page,'e1')).toHaveAttribute('aria-label',/Trắng Vua/)
  await expect(cell(page,'h1')).toHaveAttribute('aria-label',/Trắng Xe/)
})

test('en passant capture through a legal game removes the adjacent pawn', async ({page}) => {
  for (const [a,b] of [['e2','e4'],['a7','a6'],['e4','e5'],['d7','d5'],['e5','d6']]) await move(page,a,b)
  await expect(cell(page,'d6')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(cell(page,'d5')).toHaveAttribute('aria-label',/trống/)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(cell(page,'d5')).toHaveAttribute('aria-label',/Đen Tốt/)
})

test('promotion offers all four pieces, cancellation and underpromotion', async ({page}) => {
  for (const [a,b] of [['a2','a4'],['h7','h5'],['a4','a5'],['h5','h4'],['a5','a6'],['h4','h3'],['a6','b7'],['h3','g2'],['b7','a8']]) await move(page,a,b)
  const choices = page.getByRole('group',{name:'Chọn quân phong cấp'})
  await expect(choices).toBeVisible()
  for (const name of ['Hậu','Xe','Tượng','Mã']) await expect(choices.getByRole('button',{name,exact:true})).toBeVisible()
  await choices.getByRole('button',{name:'Hủy phong cấp'}).click()
  await expect(cell(page,'b7')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await cell(page,'a8').click()
  await choices.getByRole('button',{name:'Mã',exact:true}).click()
  await expect(cell(page,'a8')).toHaveAttribute('aria-label',/Trắng Mã/)
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(cell(page,'b7')).toHaveAttribute('aria-label',/Trắng Tốt/)
  await expect(cell(page,'a8')).toHaveAttribute('aria-label',/Đen Xe/)
})

test('claim repetition draw and resignation both support terminal undo redo', async ({page}) => {
  for (let i=0;i<2;i++) for (const [a,b] of [['g1','f3'],['g8','f6'],['f3','g1'],['f6','g8']]) await move(page,a,b)
  await page.getByRole('button',{name:'Yêu cầu hòa',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Hòa — lặp vị trí 3 lần')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Hòa')
  await page.getByRole('button',{name:'Ván mới',exact:true}).click()
  await page.getByRole('button',{name:'Đầu hàng',exact:true}).click()
  await page.getByRole('button',{name:'Tiếp tục chơi',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
  await page.getByRole('button',{name:'Đầu hàng',exact:true}).click()
  await page.getByRole('button',{name:'Xác nhận đầu hàng',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Đen thắng — đầu hàng.')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Lượt Trắng')
})

test('responsive board fits viewport and action controls stay beside gameplay', async ({page}) => {
  const board = page.getByRole('grid',{name:'Bàn cờ vua'}), bounds = await board.boundingBox(), viewport = page.viewportSize()
  expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(viewport.width)
  expect(Math.abs(bounds.width-bounds.height)).toBeLessThan(2)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  await expect(page.getByRole('button',{name:'Undo',exact:true})).toBeInViewport()
  await move(page,'e2','e4')
  await expect(cell(page,'e4')).toHaveAttribute('aria-label',/Trắng Tốt/)
})
